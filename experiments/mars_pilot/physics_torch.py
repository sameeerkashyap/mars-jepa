"""
Torch reimplementation of the Model-2 (simplified EBM) physics, used for:

  * the physics-residual LOSS (differentiable), matching sim_ebm.residual
    EXACTLY in definition (central-difference dT/dt, conservative FV diffusion,
    forcing-aware RHS, frost-pinned cells masked);
  * the fixed EBM forward BACKBONE for the HYBRID arm.

The residual DEFINITION (sign, columns, mask) is identical to sim_ebm.residual;
a test cross-checks this torch version against the numpy one and verifies it is
~0 on a trajectory generated by the simplified EBM itself.

Nothing here reads hidden variables.  sim_ebm / common are treated as read-only.
"""

from __future__ import annotations

import json
import os

import numpy as np
import torch

from common import SIGMA, Grid, Diffusion, load_config

_PARAMS_CACHE = os.path.join(os.path.dirname(__file__), "ebm_params.json")


def load_ebm_params(path=_PARAMS_CACHE):
    """Fitted (C_eff, D, eps, A_bare, A_ice, L, T_frost).  Cached from
    sim_ebm.fit_ebm on the unforced mismatch_scale=0 truth run."""
    with open(path) as fh:
        p = json.load(fh)
    return {k: p[k] for k in ("C_eff", "D", "eps", "A_bare", "A_ice", "L",
                              "T_frost")}


def diffusion_matrix(n, cfg=None):
    """The conservative FV operator L (n, n) from common.Diffusion (numpy)."""
    grid = Grid(n)
    return Diffusion(grid).L.copy()


def stored_dt_seconds(cfg):
    return float(cfg["time"]["output_every_sol"] * cfg["planet"]["sol_seconds"])


def _central_dt(T, dt):
    """np.gradient-equivalent central difference along time axis 0 (torch).

    T: (..., time, ncell).  Returns same shape.
    """
    dTdt = torch.empty_like(T)
    dTdt[..., 1:-1, :] = (T[..., 2:, :] - T[..., :-2, :]) / (2.0 * dt)
    dTdt[..., 0, :] = (T[..., 1, :] - T[..., 0, :]) / dt
    dTdt[..., -1, :] = (T[..., -1, :] - T[..., -2, :]) / dt
    return dTdt


class EBMResidual:
    """Differentiable Model-2 residual + physics loss.

    residual = C_eff*dT/dt - [ (1-A_bare)*S - eps*sigma*T^4 + D*(L@T) + F_a ]
    (identical to sim_ebm.residual; forcing-aware, not diffusion-only).
    """

    def __init__(self, params, n, dt, residual_scale=10.0, frost_tol_K=2.0,
                 device="cpu"):
        self.p = params
        self.dt = float(dt)
        self.scale = float(residual_scale)
        self.tol = float(frost_tol_K)
        self.device = device
        L = diffusion_matrix(n)
        self.L = torch.tensor(L, dtype=torch.float32, device=device)

    def residual(self, T, S, Fa):
        """T, S: (B, time, ncell).  Fa: (B, time) or (B, time, ncell).

        Returns (res, mask) with res in W/m^2 and mask True where usable
        (not frost-pinned, not an endpoint time row)."""
        p = self.p
        dTdt = _central_dt(T, self.dt)
        diff = T @ self.L.T                       # (B, time, ncell) = L @ T per row
        if Fa.dim() == 2:
            Fa = Fa.unsqueeze(-1)
        rhs = ((1.0 - p["A_bare"]) * S - p["eps"] * SIGMA * T ** 4
               + p["D"] * diff + Fa)
        res = p["C_eff"] * dTdt - rhs
        mask = T > (p["T_frost"] + self.tol)
        mask[..., 0, :] = False
        mask[..., -1, :] = False
        return res, mask

    def loss(self, T, S, Fa):
        res, mask = self.residual(T, S, Fa)
        if mask.sum() == 0:
            return torch.zeros((), device=T.device, dtype=T.dtype)
        r = (res / self.scale)[mask]
        return torch.mean(r ** 2)


# -----------------------------------------------------------------------------
# HYBRID backbone: fixed EBM forward step (torch, differentiable through g_theta)
# -----------------------------------------------------------------------------
class EBMBackbone:
    """Fixed simplified-EBM forward integrator, one stored step at a time, with
    the CO2 frost clamp.  Used as the hybrid backbone:

        C_eff dT/dt = [EBM RHS] + g_theta(features)

    The EBM parameters are FIXED (never trained).  The implicit diffusion
    sub-step is a precomputed (I - a*L)^-1 dense solve (64x64, differentiable).

    Ice state m is carried internally; it is INITIALIZED from the OBSERVED
    context by `init_ice_from_context` (never from hidden m).
    """

    def __init__(self, params, n, dt, m_ref=1.0, frost_init_band_K=0.5,
                 device="cpu"):
        self.p = params
        self.n = n
        self.dt = float(dt)
        self.m_ref = float(m_ref)
        self.band = float(frost_init_band_K)
        self.device = device
        L = torch.tensor(diffusion_matrix(n), dtype=torch.float32, device=device)
        self.L = L
        coeff = params["D"] / params["C_eff"]
        A = torch.eye(n, device=device) - self.dt * coeff * L
        self.diff_inv = torch.linalg.inv(A)       # implicit backward-Euler solve

    def init_ice_from_context(self, Ts_ctx):
        """Initialize ice mass from the OBSERVED context ONLY.

        Procedure (documented, never uses hidden m): a cell is deemed CO2-ice
        covered iff its LAST observed context temperature sits at/below the
        frost point within `frost_init_band_K`; such cells get a sentinel mass
        m_ref (>0, so albedo = A_ice), all others 0.

        Ts_ctx: (B, K, ncell) -> m0: (B, ncell)
        """
        last = Ts_ctx[:, -1, :]
        pinned = last <= (self.p["T_frost"] + self.band)
        return torch.where(pinned, torch.full_like(last, self.m_ref),
                           torch.zeros_like(last))

    def step(self, T, m, S, Fa, g):
        """One stored-timestep EBM update with learned correction g (W/m^2).

        T, S, g: (B, ncell); m: (B, ncell); Fa: (B,) or (B, ncell).
        Returns (T_new, m_new).  Frost clamp applied to the combined update.
        """
        p = self.p
        if Fa.dim() == 1:
            Fa = Fa.unsqueeze(-1)
        A = torch.where(m > 0.0, torch.as_tensor(p["A_ice"], device=T.device),
                        torch.as_tensor(p["A_bare"], device=T.device))
        absorbed = S * (1.0 - A)
        emitted = p["eps"] * SIGMA * T ** 4
        rhs = absorbed - emitted + Fa + g
        T_tent = T + (self.dt / p["C_eff"]) * rhs
        # implicit diffusion sub-step
        T_tent = T_tent @ self.diff_inv.T
        # frost clamp (differentiable form, exact latent bookkeeping)
        T_new, m_new = self._frost_clamp(T_tent, m)
        return T_new, m_new

    def _frost_clamp(self, T, m):
        p = self.p
        C = p["C_eff"]
        Tf = p["T_frost"]
        L = p["L"]
        freeze = T < Tf
        dm_freeze = torch.where(freeze, C * (Tf - T) / L, torch.zeros_like(T))
        m_new = m + dm_freeze
        T_new = torch.where(freeze, torch.full_like(T, Tf), T)
        melt = (~freeze) & (m_new > 0.0)
        e_avail = torch.where(melt, C * (T - Tf), torch.zeros_like(T))
        dm_poss = e_avail / L
        dm_sub = torch.minimum(dm_poss, m_new)
        dm_sub = torch.where(melt, dm_sub, torch.zeros_like(T))
        m_new = m_new - dm_sub
        T_after = Tf + (e_avail - dm_sub * L) / C
        T_new = torch.where(melt, T_after, T_new)
        return T_new, m_new
